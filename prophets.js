/* =====================================================
   إنشاء بطاقة النبي
===================================================== */

function renderProphets() {
    const grid = document.getElementById("prophetsGrid");

    if (!grid) return;

    grid.innerHTML = prophets.map((prophet, index) => `
        <button
            class="prophet-card"
            type="button"
            onclick="openStory(${index})"
        >
            <div class="prophet-icon">${prophet.icon}</div>

            <div class="prophet-number">
                ${arabicNumbers(index + 1)}
            </div>

            <h3>${prophet.name}</h3>

            <p>${prophet.intro}</p>

            <span>اقرأ القصة ←</span>
        </button>
    `).join("");
}


/* =====================================================
   فتح القصة
===================================================== */

function openStory(index) {
    const prophet = prophets[index];

    if (!prophet) return;

    const reader = document.getElementById("storyReader");

    const title = document.getElementById("storyTitle");

    const content = document.getElementById("storyContent");

    if (!reader || !title || !content) return;

    title.innerHTML = `
        <span class="story-header-icon">
            ${prophet.icon}
        </span>
        ${prophet.name}
    `;

    content.innerHTML = `
        <div class="story-intro">
            <div class="story-intro-icon">📖</div>
            <p>${prophet.intro}</p>
        </div>

        <div class="story-timeline">
            ${prophet.story.map((paragraph, i) => `
                <div class="story-event">
                    <div class="story-event-number">
                        ${arabicNumbers(i + 1)}
                    </div>

                    <div class="story-event-body">
                        <p>${paragraph}</p>
                    </div>
                </div>
            `).join("")}
        </div>

        <div class="story-references">
            <h3>📖 مواضع القصة في القرآن</h3>

            <p class="story-note">
                اضغط على أي موضع للانتقال مباشرة إلى السورة والآية في صفحة القرآن.
            </p>

            <div class="references-list">
                ${prophet.references.map(ref => {
                    const [surah, surahNumber, ayahNumber] = ref;

                    return `
                        <button
                            type="button"
                            class="story-ref"
                            onclick="openQuranAyah(${surahNumber}, ${ayahNumber})"
                        >
                            📖 سورة ${surah}
                            — الآية ${arabicNumbers(ayahNumber)}
                            <span>↗</span>
                        </button>
                    `;
                }).join("")}
            </div>
        </div>
    `;

    reader.classList.add("show");

    reader.scrollIntoView({
        behavior: "smooth",
        block: "start"
    });
}


/* =====================================================
   الانتقال إلى القرآن
===================================================== */

function openQuranAyah(surahNumber, ayahNumber) {
    window.location.href =
        `quran.html?surah=${surahNumber}&ayah=${ayahNumber}`;
}


/* =====================================================
   إغلاق القصة
===================================================== */

function closeStory() {
    const reader = document.getElementById("storyReader");

    if (reader) {
        reader.classList.remove("show");
    }
}


/* =====================================================
   أرقام عربية
===================================================== */

function arabicNumbers(number) {
    return String(number).replace(
        /\d/g,
        digit => "٠١٢٣٤٥٦٧٨٩"[digit]
    );
}


